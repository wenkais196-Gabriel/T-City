-- server/npc_budget.lua — FIT-07 unified NPC spawn budget (server authority).
--
-- Both NPC-producing paths must go through this service:
--   * p2_system.lua  RequestBackup -> Acquire('backup', requestId, citizenid)
--   * p4_npc.lua     CreateNpcCallout -> Acquire('callout', budgetId, citizenid)
--
-- Every successful Acquire is paired with exactly one Release on every exit
-- path (backupEnded, playerDropped, callout result, watcher close, TTL sweep).
-- The entries are process-local on purpose: a resource restart removes the
-- NPCs and their slots together, and police_audit is the durable record.
--
-- Public API:
--   NPCBudget.Acquire(kind, id, citizenid) -> true | false, error
--   NPCBudget.Release(id, reason)          -> true | false (idempotent)
--   NPCBudget.Sweep()                      -> number released
--   NPCBudget.Get() / GetNpcBudget()       -> {used, max, byPlayer, entries}
--
-- `id` is generated by the server (backup request id, callout budget id) and
-- is never accepted from a client.

local entries = {} -- [normalized id] = { id, kind, citizenid, slots, at }

local function now()
    return os.time()
end

local function auditNpc(action, target, detail, citizenid)
    -- 唯一写者见 server/audit.lua；actor_kind 保持 'system'
    return PoliceAudit.Write(citizenid, action, target, detail, 'system')
end

--- Reserve `kind` for `id` against `citizenid`.
--- The entry is stored before the yielding audit insert so two requests in
--- the same tick cannot both observe the pre-insert usage.
--- @param kind string 'backup' | 'callout'
--- @param id string|number server-generated unique id
--- @param citizenid string owner of the slots
--- @return true|false, string|nil error
function NPCBudget.Acquire(kind, id, citizenid)
    local key = NPCBudget.Normalize(id)
    local admitted, costOrError = NPCBudget.CanAcquire(entries, kind, key, citizenid)
    if not admitted then return false, costOrError end

    entries[key] = {
        id = key,
        kind = kind,
        citizenid = citizenid,
        slots = costOrError,
        at = now(),
    }
    auditNpc('npc.spawn', key, ('%s:%d'):format(kind, costOrError), citizenid)
    return true
end

--- Release one slot record. Idempotent: a second call for the same id (or an
--- unknown id) returns false and writes no audit row.
--- @param id string|number
--- @param reason string|nil audit detail, e.g. 'backup_ended'
--- @return boolean released
function NPCBudget.Release(id, reason)
    local key = NPCBudget.Normalize(id)
    if not key then return false end
    local entry = entries[key]
    if not entry then return false end

    entries[key] = nil
    local why = tostring(reason or '')
    if why == '' then why = 'released' end
    auditNpc('npc.despawn', key, why, entry.citizenid)
    return true
end

--- Release every record older than the TTL. The sweep runs on its own 60s
--- timer after resource start; entries are removed before the yielding audit
--- so a slow database cannot resurrect a stale slot.
--- @return number released
function NPCBudget.Sweep()
    local current = now()
    local released = 0
    for key, entry in pairs(entries) do
        if current - (tonumber(entry.at) or current) > NPCBudget.TTL_SECONDS then
            entries[key] = nil
            released = released + 1
            auditNpc('npc.stale', key,
                ('%s:%d'):format(tostring(entry.kind), tonumber(entry.slots) or 0),
                entry.citizenid)
        end
    end
    return released
end

--- Read-only snapshot for the MDT/agent: totals plus one copy per entry.
--- @return table { used, max, byPlayer, entries }
function NPCBudget.Get()
    local used, byPlayer = NPCBudget.Usage(entries)
    local list = {}
    for _, entry in pairs(entries) do
        list[#list + 1] = {
            id = entry.id,
            kind = entry.kind,
            citizenid = entry.citizenid,
            slots = entry.slots,
            at = entry.at,
        }
    end
    table.sort(list, function(a, b) return a.id < b.id end)
    return {
        used = used,
        max = NPCBudget.MAX_GLOBAL,
        byPlayer = byPlayer,
        entries = list,
    }
end

--- Global read-only accessor exported for the MDT and the agent bridge.
function GetNpcBudget()
    return NPCBudget.Get()
end

exports('GetNpcBudget', GetNpcBudget)

AddEventHandler('onResourceStart', function(resourceName)
    if resourceName ~= GetCurrentResourceName() then return end
    NPCBudget.Sweep()
    CreateThread(function()
        while true do
            Wait(NPCBudget.SWEEP_INTERVAL_MS)
            NPCBudget.Sweep()
        end
    end)
end)

print('[custom-police] NPC spawn budget loaded')
