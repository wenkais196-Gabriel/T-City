def rel(p: str) -> str:
    return os.path.relpath(p, REPO).replace("\\", "/")


def is_generated(path: str) -> bool:
    """构建产物（`<!-- @generated by ... -->` 打头）不是文档，和 INDEX.md 一样排除在范围外。

    它们由生成器整体重写，加 frontmatter 会立刻被判 stale（tools/agent_tools.py --check）。
    """
    try:
        with open(path, encoding="utf-8", errors="ignore") as fh:
            return GENERATED_MARK in fh.readline(200)
    except OSError:
        return False


def iter_docs() -> list[str]:
    out: list[str] = []
    for root in ROOTS:
        base = os.path.join(REPO, root)
        if not os.path.isdir(base):
            continue
        for dirpath, dirnames, files in os.walk(base):
            dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
            for f in files:
                if f.endswith(".md") and f != "INDEX.md":
                    p = os.path.join(dirpath, f)
                    if is_generated(p):
                        continue
                    out.append(p)
    for f in ROOT_FILES:
        p = os.path.join(REPO, f)
        if os.path.isfile(p):
            out.append(p)
    return sorted(set(out))


# ---------------------------------------------------------------- frontmatter

FM_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.S)


def parse_frontmatter(text: str) -> tuple[dict, int]:
    """返回 (meta, 正文起始行号)。只支持扁平的 key: value 与 [a, b]。"""
    m = FM_RE.match(text)
    if not m:
        return {}, 0
    meta: dict = {}
    for raw in m.group(1).splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        k, v = line.split(":", 1)
        k, v = k.strip(), v.strip()
        if v.startswith("[") and v.endswith("]"):
            inner = v[1:-1].strip()
            meta[k] = [x.strip().strip("'\"") for x in inner.split(",") if x.strip()] if inner else []
        else:
            meta[k] = v.strip("'\"")
    return meta, m.group(0).count("\n")


def render_frontmatter(meta: dict) -> str:
    order = ["id", "type", "status", "system", "owner", "updated", "review_by",
             "supersedes", "superseded_by", "tracks", "source_of_truth"]
    keys = [k for k in order if k in meta] + [k for k in meta if k not in order]
    lines = ["---"]
    for k in keys:
        v = meta[k]
        if isinstance(v, list):
            lines.append(f"{k}: [{', '.join(v)}]")
        else:
            lines.append(f"{k}: {v}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def load(p: str) -> tuple[dict, str, int]:
    text = open(p, encoding="utf-8", errors="ignore").read()
    meta, offset = parse_frontmatter(text)
    return meta, text, offset


def first_heading(text: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return "(无标题)"


# ---------------------------------------------------------------- plan status
#
# 计划正文里的「✅ 完成 / 🟡 进行中」是散文，机器读不到。这里定义一段可校验的
# 围栏块（frontmatter 用 `plan_status: 1` 开关），只放 id/state/ev/date 四列：
# 依赖、阻塞、拍板仍留在正文，不进块。
#
# 三档语义（闸门文案与看板文案共用这三个词）：
#   未登记 = 该计划没有 `plan_status: 1` 或没有块；
#   未取证 = 标了 done，但 ev 不是单个 #PR、也不是仓内存在的相对路径；
#   未开始 = 显式 todo。

PLAN_STATUS_KEY = "plan_status"
PLAN_STATUS_FENCE = "plan-status"
PLAN_STATUS_STATES = ("todo", "wip", "done")
#: 单片计划的唯一合法行 id：正文没有切片表时，整份计划就是一个不可再分的单位。
#: 不强制"先划片再登记"——为一次性计划发明切片只会制造假粒度（35 份 plan 里 15 份如此）。
SINGLE_UNIT_ID = "ALL"
SLICE_HEADERS = {"#", "片", "切片", "分片", "阶段", "步骤", "工作项"}
SLICE_ID_RE = re.compile(r"(?:Step \d+|[A-Z]\d*[a-z]?(?:-\d+)?)")
PR_ONE_RE = re.compile(r"#\d+")
PR_RANGE_RE = re.compile(r"#\d+\s*[-–—]\s*#?\d+")
PLAN_DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}")

TIER_UNREGISTERED = "未登记"
TIER_UNVERIFIED = "未取证"
TIER_TODO = "未开始"


def has_plan_status_block(body: str) -> bool:
    # 只认顶格的围栏；文档里用 4 空格缩进展示示例时不会被当成真实块。
    fence = "```" + PLAN_STATUS_FENCE
    return any(line.rstrip() == fence for line in body.splitlines())


def parse_plan_status(body: str) -> tuple[list[dict], list[str]]:
    """解析 `plan-status` 围栏块，返回 (rows, errors)。

    rows 的每项：``{"id", "state", "ev", "date", "line"}``。这里只校验形状
    （4 列 / state / date / id 唯一）；ev 是否可复核需要仓库路径，放在 --check 里判。
    """
    rows: list[dict] = []
    errors: list[str] = []
    blocks: list[list[tuple[int, str]]] = []
    current: list[tuple[int, str]] | None = None
    open_line = 0

    for lineno, raw in enumerate(body.splitlines(), 1):
        line = raw.rstrip()
        if current is None:
            if line == "```" + PLAN_STATUS_FENCE:
                current = []
                open_line = lineno
            continue
        if line == "```":
            blocks.append(current)
            current = None
            continue
        current.append((lineno, raw))
    if current is not None:
        errors.append(f"plan-status 块未闭合（第 {open_line} 行开栅栏）")
        blocks.append(current)
    if len(blocks) > 1:
        errors.append(f"只允许一个 plan-status 块，实际 {len(blocks)} 个")

    seen: set[str] = set()
    for block in blocks:
        for lineno, raw in block:
            if not raw.strip():
                continue
            cells = [c.strip() for c in raw.split("|")]
            if len(cells) != 4:
                errors.append(
                    f"plan-status 第 {lineno} 行：应有 4 列（id | state | ev | date），"
                    f"实际 {len(cells)} 列")
                continue
            rid, state, ev, date = cells
            if not rid:
                errors.append(f"plan-status 第 {lineno} 行：id 为空")
            elif rid != SINGLE_UNIT_ID and not SLICE_ID_RE.fullmatch(rid):
                errors.append(
                    f"plan-status 第 {lineno} 行：id=`{rid}` 不是切片 ID 形状"
                    f"（如 S1 / P1-4 / Step 0；单片计划用 `{SINGLE_UNIT_ID}`）")
            if state not in PLAN_STATUS_STATES:
                errors.append(
                    f"plan-status 第 {lineno} 行：state=`{state}` 不在 "
                    f"{list(PLAN_STATUS_STATES)}")
            if date != "-" and not (PLAN_DATE_RE.fullmatch(date) and parse_date(date)):
                errors.append(
                    f"plan-status 第 {lineno} 行：日期 date=`{date}` 不是 YYYY-MM-DD 或 -")
            if rid:
                if rid in seen:
                    errors.append(f"plan-status 第 {lineno} 行：id=`{rid}` 重复")
                seen.add(rid)
            rows.append({"id": rid, "state": state, "ev": ev, "date": date, "line": lineno})
    return rows, errors


def _table_cells(line: str) -> list[str]:
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|"):
        s = s[:-1]
    return [c.strip() for c in s.split("|")]


def _is_table_separator(line: str) -> bool:
    cells = _table_cells(line)
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", c) for c in cells)


def _clean_cell(cell: str) -> str:
    return cell.replace("**", "").replace("__", "").replace("`", "").strip()


def slice_ids_from_body(body: str) -> set[str]:
    """正文切片表首列的 ID 集。只认首列表头在 SLICE_HEADERS 里的表，跳过代码块。"""
    ids: set[str] = set()
    lines = body.splitlines()
    in_fence = False
    i = 0
    while i < len(lines) - 1:
        stripped = lines[i].strip()
        if stripped.startswith("```"):
            in_fence = not in_fence
            i += 1
            continue
        if in_fence or not stripped.startswith("|"):
            i += 1
            continue
        if _is_table_separator(lines[i + 1]):
            header = [_clean_cell(c) for c in _table_cells(stripped)]
            head = header[0] if header else ""
            # `#` 是通用序号表头：只有同时出现「任务/切片/状态」列时才算切片表，
            # 否则判据清单（如 G1..G18）会被误当成切片。
            numbered_work = head == "#" and bool({"任务", "切片", "状态"} & set(header[1:]))
            if head in SLICE_HEADERS and (head != "#" or numbered_work):
                j = i + 2
                while j < len(lines) and lines[j].strip().startswith("|"):
                    cells = _table_cells(lines[j])
                    cell = _clean_cell(cells[0]) if cells else ""
                    match = SLICE_ID_RE.match(cell)
                    if match:
                        ids.add(match.group(0))
                    j += 1
                i = j
                continue
        i += 1
    return ids


def plan_evidence(ev: str) -> str:
    """判断 ev 可复核性：``verified`` / ``unverified`` / ``invalid``。"""
    ev = ev.strip().replace("\\", "/")
    if ev == "-" or PR_RANGE_RE.fullmatch(ev):
        return "unverified"          # `-` 与 PR 区间都不算证据
    if PR_ONE_RE.fullmatch(ev):
        return "verified"
    if not ev or ev.startswith("/") or re.match(r"^[A-Za-z]:", ev):
        return "invalid"
    norm = os.path.normpath(ev)
    if norm.startswith("..") or os.path.isabs(norm):
        return "invalid"
    return "verified" if os.path.exists(os.path.join(REPO, norm)) else "invalid"


def check_plan_status(
        rp: str, meta: dict, body: str, errors: list[str], warns: list[str]) -> None:
    """只对带 `plan_status` 开关或块的文件追加校验；其余文档行为不变。"""
    has_key = PLAN_STATUS_KEY in meta
    has_block = has_plan_status_block(body)
    if not has_key and not has_block:
        return

    if has_key and str(meta.get(PLAN_STATUS_KEY, "")).strip() != "1":
        errors.append(
            f"{rp}: `plan_status={meta.get(PLAN_STATUS_KEY)}` 不支持（只允许 1）")
    if has_key and not has_block:
        errors.append(
            f"{rp}: {TIER_UNREGISTERED} plan-status：frontmatter 有 "
            "`plan_status: 1`，正文缺少 ```plan-status 块")
        return
    if has_block and not has_key:
        errors.append(
            f"{rp}: {TIER_UNREGISTERED} plan_status 开关：正文有 plan-status 块，"
            "frontmatter 缺少 `plan_status: 1`")

    rows, parse_errors = parse_plan_status(body)
    errors.extend(f"{rp}: {e}" for e in parse_errors)

    table_ids = slice_ids_from_body(body)
    row_ids = [r["id"] for r in rows if r["id"]]
    if not table_ids:
        # 单片计划（15/35 份 active 没有切片表）：只允许一行 `ALL`。
        # 不强制它们先划片——为了一份一次性的 police 计划发明切片只会制造假粒度。
        if row_ids != [SINGLE_UNIT_ID]:
            errors.append(
                f"{rp}: 正文没有切片表 —— plan-status 只允许单行 "
                f"`{SINGLE_UNIT_ID} | state | ev | date`（当前 {len(row_ids)} 行）")
    else:
        missing = sorted(table_ids - set(row_ids))
        extra = sorted(set(row_ids) - table_ids)
        if missing:
            errors.append(f"{rp}: plan-status 缺少切片 ID：{', '.join(missing)}")
        if extra:
            errors.append(f"{rp}: plan-status 切片 ID 不在正文切片表：{', '.join(extra)}")

    for row in rows:
        if row["state"] != "done":
            continue
        verdict = plan_evidence(row["ev"])
        if verdict == "unverified":
            warns.append(
                f"{rp}: {TIER_UNVERIFIED}：`{row['id']}` 标 done 但 ev=`{row['ev']}`"
                "（需要单个 #PR 或仓内存在的相对路径；PR 区间不算证据）")
        elif verdict == "invalid":
            errors.append(
                f"{rp}: plan-status `{row['id']}` 的 ev 不可复核：`{row['ev']}`"
                "（应为单个 #PR 或仓内存在的相对路径）")


# ---------------------------------------------------------------- 校验

def today() -> dt.date:
    return dt.date.today()


def parse_date(s: str) -> dt.date | None:
    try:
        return dt.date.fromisoformat(s)
    except Exception:
        return None


def check(docs: list[str], index_path: str) -> tuple[list[str], list[str], dict]:
    errors: list[str] = []
    warns: list[str] = []
    meta_cache: dict[str, dict] = {}
    ids: dict[str, str] = {}
    titles: dict[str, str] = {}
    sot: dict[tuple[str, str], list[str]] = {}
    sot_topics: dict[str, str] = {}
    registered = 0

    for p in docs:
        rp = rel(p)
        meta, text, offset = load(p)
        meta_cache[rp] = meta
        title = first_heading(text)
        if title in titles and title != "(无标题)":
            warns.append(f"重复标题：「{title}」{titles[title]} ↔ {rp}")
        titles.setdefault(title, rp)

        check_plan_status(rp, meta, text[offset:], errors, warns)

        if not meta:
            warns.append(f"未登记（无 frontmatter）：{rp}")
            continue
        registered += 1

        for k in REQUIRED:
            if not meta.get(k):
                errors.append(f"{rp}: 缺少必填字段 `{k}`")

        t, st, sysname = meta.get("type"), meta.get("status"), meta.get("system")
        if t and t not in TYPES:
            errors.append(f"{rp}: type=`{t}` 不在 {TYPES}")
        if st and st not in STATUSES:
            errors.append(f"{rp}: status=`{st}` 不在 {STATUSES}")
        if sysname and sysname not in SYSTEMS:
            errors.append(f"{rp}: system=`{sysname}` 不在 {SYSTEMS}")

        for key in ("updated", "review_by"):
            v = meta.get(key)
            if not v:
                continue
            d = parse_date(v)
            if d is None:
                errors.append(f"{rp}: `{key}={v}` 不是 YYYY-MM-DD")
            elif key == "updated" and d > today():
                errors.append(f"{rp}: `updated` 在未来（{v}）")
            elif key == "review_by" and d < today():
                warns.append(f"{rp}: `review_by` 已过期（{v}），请复审并顺延")

        if t in REVIEW_REQUIRED and not meta.get("review_by"):
            errors.append(f"{rp}: type={t} 必须给 review_by（复审到期日）")

        rid = meta.get("id")
        if rid:
            if rid in ids:
                errors.append(f"id 重复：`{rid}` {ids[rid]} ↔ {rp}")
            ids[rid] = rp
            if not re.fullmatch(r"[a-z0-9][a-z0-9-]{2,63}", rid):
                warns.append(f"{rp}: id=`{rid}` 建议用小写 kebab-case")

        if meta.get("source_of_truth") in ("true", "yes"):
            topic = meta.get("topic")
            if topic:
                if topic in sot_topics:
                    errors.append(f"topic=`{topic}` 有两个 source_of_truth：{sot_topics[topic]} ↔ {rp}")
                sot_topics[topic] = rp
            elif t and sysname:
                sot.setdefault((sysname, t), []).append(rp)

        if st == "superseded" and not meta.get("superseded_by"):
            warns.append(f"{rp}: status=superseded 但未写 superseded_by")

        rb = parse_date(meta.get("review_by") or "")
        if rb and rb < today() and st == "active":
            warns.append(f"复审已过期：{rp}（review_by={meta['review_by']}）")

        base = os.path.basename(p)
        if base != "README.md" and not re.fullmatch(r"[a-z0-9][a-z0-9._-]*\.md", base) \
                and not re.fullmatch(r"[A-Z][A-Z0-9_-]*\.md", base):
            warns.append(f"{rp}: 文件名既不是小写 kebab-case 也不是全大写规范名")

    # 同一 (system,type) 多个 SoT 且都没写 topic → 提醒区分主题
    for (sysname, t), paths in sot.items():
        if len(paths) > 1:
            warns.append(
                f"(system={sysname}, type={t}) 有 {len(paths)} 份 source_of_truth，"
                f"请给各自加 `topic` 区分：{', '.join(paths)}")

    # supersedes 双向一致（比较 id，不是文件路径）
    for rp, meta in meta_cache.items():
        cur_id = meta.get("id")
        for sid in meta.get("supersedes") or []:
            other = ids.get(sid)
            if not other:
                errors.append(f"{rp}: supersedes 指向不存在的 id `{sid}`")
            elif cur_id not in (meta_cache.get(other, {}).get("superseded_by") or []):
                warns.append(f"{rp}: supersedes `{sid}` 但对方没有 superseded_by（应为 `{cur_id}`）")

    # 断链（先剥掉行内代码，避免把 `[a](b.md)` 这种示例当成真链接）
    legacy = legacy_dirs()
    for p in docs:
        rp = rel(p)
        if in_legacy(rp, legacy):
            continue
        text = open(p, encoding="utf-8", errors="ignore").read()
        text = re.sub(r"`[^`\n]*`", "", text)
        for target in re.findall(r"\]\(([^)#\s]+\.md)", text):
            if target.startswith(("http://", "https://", "file://")):
                continue
            if not os.path.exists(os.path.normpath(os.path.join(os.path.dirname(p), target))):
                warns.append(f"断链：{rp} → {target}")

    # 索引是否最新（比内容，不比「生成时间」——否则每天零点后无改动也报过期）
    if os.path.exists(index_path):
        if not index_is_current(docs):
            warns.append("docs/INDEX.md 不是最新（运行 `python tools/docs_lifecycle.py --index`）")
    else:
        warns.append("docs/INDEX.md 不存在（运行 --index 生成）")

    board_path = os.path.join(REPO, BOARD_REL)
    if os.path.exists(board_path):
        if not board_is_current(docs):
            warns.append(f"{BOARD_REL} 不是最新（运行 `python tools/docs_lifecycle.py --board`）")
    else:
        warns.append(f"{BOARD_REL} 不存在（运行 --board 生成）")

    stats = {
        "total": len(docs), "registered": registered, "unregistered": len(docs) - registered,
        "errors": len(errors), "warnings": len(warns),
    }
    return errors, warns, stats


# ---------------------------------------------------------------- 看板

BOARD_MARKER = "<!-- @generated by tools/docs_lifecycle.py --board；不要手改 -->"


def board_link(path: str) -> str:
    """BOARD.md 位于 docs/plan/，把仓内路径转成相对链接。"""
    target = os.path.relpath(
        os.path.join(REPO, path), os.path.join(REPO, "docs", "plan"))
    return target.replace("\\", "/")


def plan_status_counts(rows: list[dict]) -> tuple[int, int, str, str]:
    """返回 (已证明, 未取证, 当前片, 最后更新)。只读块，不猜散文。"""
    proven = unverified = 0
    dates: list[str] = []
    current = "-"
    for row in rows:
        if row["state"] == "done":
            if plan_evidence(row["ev"]) == "verified":
                proven += 1
            else:
                unverified += 1
        if row["date"] != "-" and PLAN_DATE_RE.fullmatch(row["date"]):
            dates.append(row["date"])
    for row in rows:
        if row["state"] != "done":
            label = TIER_TODO if row["state"] == "todo" else row["state"]
            who = "整体" if row["id"] == SINGLE_UNIT_ID else row["id"]
            current = f"{who} {label}"
            break
    return proven, unverified, current, max(dates) if dates else "-"


def build_board(docs: list[str]) -> str:
    """生成 docs/plan/BOARD.md：active 在前、未登记在最后，同组按路径。"""
    plans: list[dict] = []
    for p in docs:
        meta, text, offset = load(p)
        if meta.get("type") != "plan":
            continue
        body = text[offset:]
        has_block = has_plan_status_block(body)
        rows = parse_plan_status(body)[0] if has_block else []
        plans.append({
            "path": rel(p), "title": first_heading(text),
            "status": meta.get("status", TIER_UNREGISTERED),
            "has_block": has_block, "rows": rows,
        })

    def group(item: dict) -> int:
        if not item["has_block"]:
            return 2
        return 0 if item["status"] == "active" else 1

    plans.sort(key=lambda item: (group(item), item["path"]))

    out = [
        BOARD_MARKER,
        "# 计划看板（自动生成）",
        "",
        "> 数据源＝各计划正文的 plan-status 块。未登记＝该计划没有块；"
        "未取证＝done 但 ev 不可复核。",
        "> 手改无效：下次 --board 会覆盖。",
        "",
        "| 计划 | 状态 | 片 | 已证明 | 未取证 | 当前片 | 最后更新 |",
        "|---|---|---|---|---|---|---|",
    ]
    for item in plans:
        if item["has_block"]:
            proven, unverified, current, updated = plan_status_counts(item["rows"])
            only = len(item["rows"]) == 1 and item["rows"][0]["id"] == SINGLE_UNIT_ID
            slices = "单片" if only else str(len(item["rows"]))
        else:
            proven = unverified = 0
            current = updated = "-"
            slices = TIER_UNREGISTERED
        title = item["title"].replace("|", "\\|")
        out.append(
            f"| [{title}]({board_link(item['path'])}) | {item['status']} | {slices} | "
            f"{proven} | {unverified} | {current} | {updated} |")
    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- 索引

def index_is_current(docs: list[str]) -> bool:
    """INDEX 是否与当前文档树一致（纯内容比较，生成物里不再有"生成时间"）。

    为什么去掉日期：INDEX 是生成物，CI 用 `--index` 后 `git diff --quiet` 判它是否最新；
    带时间戳的生成物**永远**在跨天时 diff 非空，CI 每天红一次，且只能靠重新生成消掉。
    同一类问题在本仓已有先例（`tools/agent_tools.json` 的 `generated` 字段被记过 F-17）。
    """
    path = os.path.join(REPO, "docs", "INDEX.md")
    try:
        have = open(path, encoding="utf-8", errors="ignore").read()
    except OSError:
        return False
    return build_index(docs).strip() == have.strip()


def board_is_current(docs: list[str]) -> bool:
    """BOARD.md 是否与当前文档树一致：生成物既不许手改，也不许过期。

    实测过的真实故障：另一个 PR 把一份 md 改了名，BOARD 里那行链接立刻指错，
    而块校验照样全绿 —— 所以新鲜度必须自己判，不能靠"生成过就算对"。
    """
    path = os.path.join(REPO, BOARD_REL)
    try:
        have = open(path, encoding="utf-8", errors="ignore").read()
    except OSError:
        return False
    return build_board(docs).strip() == have.strip()


def build_index(docs: list[str]) -> str:
    rows: dict[str, list[dict]] = {s: [] for s in SYSTEMS}
    unregistered: list[dict] = []
    for p in docs:
        meta, text, _ = load(p)
        item = {
            "path": rel(p), "title": first_heading(text),
            "type": meta.get("type", "—"), "status": meta.get("status", "未登记"),
            "updated": meta.get("updated", "—"), "review_by": meta.get("review_by", "—"),
            "sot": meta.get("source_of_truth") in ("true", "yes"),
            "owner": meta.get("owner", "—"),
        }
        sysname = meta.get("system")
        if not meta or sysname not in rows:
            unregistered.append(item)
        else:
            rows[sysname].append(item)

    total = len(docs)
    reg = total - len(unregistered)
    cnt = lambda st: sum(1 for v in rows.values() for i in v if i["status"] == st)  # noqa: E731

    out = [
        "# 文档索引（自动生成，请勿手改）",
        "",
        "> 由 `python tools/docs_lifecycle.py --index` 生成。规范："
        "[`standards/doc-lifecycle.md`](standards/doc-lifecycle.md)。",
        "",
        f"**文档总数**：{total} ｜ "
        f"**已登记**：{reg} ｜ **未登记**：{len(unregistered)}",
        "",
        f"**状态分布**：✅ active {cnt('active')} ・ 🟡 draft {cnt('draft')} ・ "
        f"🔍 review {cnt('review')} ・ 📌 final {cnt('final')} ・ "
        f"♻️ superseded {cnt('superseded')} ・ 📦 archived {cnt('archived')}",
        "",
        "## 按系统",
        "",
    ]
    for sysname in SYSTEMS:
        items = sorted(rows[sysname], key=lambda i: (i["type"], i["path"]))
        if not items:
            continue
        out.append(f"### {sysname}（{len(items)}）")
        out.append("")
        out.append("| 文档 | 类型 | 状态 | 更新 | 复审 | SoT | 路径 |")
        out.append("|---|---|---|---|---|---|---|")
        for i in items:
            out.append(
                f"| [{i['title']}]({link_from_docs(i['path'])}) | {i['type']} | "
                f"{STATUS_BADGE.get(i['status'], i['status'])} | "
                f"{i['updated']} | {i['review_by']} | {'★' if i['sot'] else ''} | `{i['path']}` |"
            )
        out.append("")

    if unregistered:
        out.append(f"## 未登记（{len(unregistered)}）—— 待补 frontmatter")
        out.append("")
        out.append("| 文档 | 推断类型 | 路径 |")
        out.append("|---|---|---|")
        for i in sorted(unregistered, key=lambda x: x["path"]):
            out.append(f"| {i['title']} | {guess_type(i['path'])} | `{i['path']}` |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def link_from_docs(path: str) -> str:
    """INDEX.md 位于 docs/，把仓内路径转成相对链接。"""
    if path.startswith("docs/"):
        return path[len("docs/"):]
    return "../" + path


def guess_type(path: str) -> str:
    p = path.lower()
    if "/adr/" in p or "decision" in p:
        return "adr"
    if "blueprint" in p or "design" in p or "spec" in p:
        return "spec"
    if "audit" in p or "report" in p or "acceptance" in p or "review" in p:
        return "audit"
    if "research" in p or "analysis" in p:
        return "research"
    if "manual" in p or "reference" in p or "index" in p or "guide" in p:
        return "manual"
    if "progress" in p or "plan" in p or "roadmap" in p or "versions/" in p:
        return "plan"
    if "runbook" in p or "sop" in p or "workspace" in p:
        return "runbook"
    if "standard" in p or p.endswith("agents.md") or p.endswith("claude.md") or p.endswith("contributing.md"):
        return "meta"
    return "manual"


# ---------------------------------------------------------------- 报告

def _read_for_corpus(path: str) -> str:
    """读一份文本作为"谁引用过"的语料。读不了就返回空串——

    缺文件/编码异常不该让整份报告挂掉；但这里只吞 `OSError`（含 UnicodeDecodeError 之外的 IO 问题），
    不吞 `Exception`：真正的编程错误要冒出来，而不是被当成"这份文件没人引用"。
    """
    try:
        with open(path, encoding="utf-8", errors="ignore") as fh:
            return fh.read()
    except OSError:
        return ""


def _corpus_text() -> str:
    """把「谁引用过」的语料拼起来：范围内的 md/py/lua/yml/cfg + 根文件。

    只排除**自动生成**的文档总索引（`docs/INDEX.md`）——它列了全部文档，把它算进语料会让
    孤儿恒为 0、指标失效。手写的 `INDEX.md`（如 `docs/client/ux/INDEX.md`）是真正的导航宿主，
    必须计入，否则"被人索引着的文档"会被误报成孤儿（2026-11-16 实测误报 5 篇）。
    """
    generated = os.path.normpath(os.path.join(REPO, "docs", "INDEX.md"))
    suffixes = (".md", ".py", ".lua", ".yml", ".cfg")
    chunks: list[str] = []
    for root in ROOTS:
        for dirpath, dirnames, filenames in os.walk(os.path.join(REPO, root)):
            dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
            for name in filenames:
                path = os.path.join(dirpath, name)
                if name.endswith(suffixes) and os.path.normpath(path) != generated:
                    chunks.append(_read_for_corpus(path))
    for name in ROOT_FILES:
        path = os.path.join(REPO, name)
        if os.path.isfile(path):
            chunks.append(_read_for_corpus(path))
    return "".join(chunks)


def report(docs: list[str], out_json: str) -> dict:
    records = []
    for p in docs:
        meta, text, _ = load(p)
        st = os.stat(p)
        records.append({
            "path": rel(p), "title": first_heading(text),
            "registered": bool(meta), "type": meta.get("type"), "status": meta.get("status"),
            "system": meta.get("system"), "updated": meta.get("updated"),
            "review_by": meta.get("review_by"),
            "mtime": dt.date.fromtimestamp(st.st_mtime).isoformat(),
            "bytes": st.st_size,
            "sha256": hashlib.sha256(re.sub(r"\s+", "", text).encode()).hexdigest()[:16],
        })
    # 内容重复
    seen: dict[str, list[str]] = {}
    for r in records:
        seen.setdefault(r["sha256"], []).append(r["path"])
    dups = [v for v in seen.values() if len(v) > 1]
    # 孤儿：basename 不出现在任何 md/代码里（语料构建见 _corpus_text）。
    haystack = _corpus_text()
    orphans = [r["path"] for r in records if os.path.basename(r["path"]) not in haystack]

    summary = {
        "generated": today().isoformat(),
        "total": len(records),
        "registered": sum(1 for r in records if r["registered"]),
        "unregistered": sum(1 for r in records if not r["registered"]),
        "orphans": len(orphans),
        "duplicate_groups": len(dups),
        "by_type": {},
        "by_status": {},
    }
    for r in records:
        if r["type"]:
            summary["by_type"][r["type"]] = summary["by_type"].get(r["type"], 0) + 1
        if r["status"]:
            summary["by_status"][r["status"]] = summary["by_status"].get(r["status"], 0) + 1

    payload = {"summary": summary, "duplicates": dups, "orphans": orphans, "docs": records}
    with open(out_json, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=1)
    return payload


# ---------------------------------------------------------------- adopt

def adopt(paths: list[str], write: bool) -> None:
    for p in paths:
        meta, text, _ = load(p)
        if meta:
            print(f"SKIP 已有 frontmatter: {rel(p)}")
            continue
        slug = re.sub(r"[^a-z0-9]+", "-", os.path.splitext(os.path.basename(p))[0].lower()).strip("-")
        today_s = today().isoformat()
        guess = {
            "id": slug, "type": guess_type(rel(p)), "status": "active",
            "system": "meta", "owner": "hermes", "updated": today_s,
        }
        if guess["type"] in REVIEW_REQUIRED:
            guess["review_by"] = (today() + dt.timedelta(days=90)).isoformat()
        block = render_frontmatter(guess)
        if not write:
            print(f"--- 建议 frontmatter：{rel(p)}\n{block}")
            continue
        open(p, "w", encoding="utf-8").write(block + "\n" + text.lstrip("\n"))
        print(f"ADOPT {rel(p)}")


# ---------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description="T-City 文档生命周期工具")
    ap.add_argument("--check", action="store_true", help="校验并返回退出码")
    ap.add_argument("--index", action="store_true", help="生成 docs/INDEX.md")
    ap.add_argument("--board", action="store_true", help="生成 docs/plan/BOARD.md")
    ap.add_argument("--report", action="store_true", help="生成 docs/_lifecycle.json 与摘要")
    ap.add_argument("--adopt", nargs="*", help="为指定文档补最小 frontmatter")
    ap.add_argument("--yes", action="store_true", help="配合 --adopt 直接写入")
    ap.add_argument("--verbose", action="store_true", help="打印全部告警")
    args = ap.parse_args()

    docs = iter_docs()
    index_path = os.path.join(REPO, "docs", "INDEX.md")

    if args.adopt is not None:
        adopt([os.path.join(REPO, x) if not os.path.isabs(x) else x for x in args.adopt], args.yes)
        return 0

    if args.index:
        os.makedirs(os.path.dirname(index_path), exist_ok=True)
        open(index_path, "w", encoding="utf-8").write(build_index(docs))
        print(f"wrote {rel(index_path)} ({len(docs)} docs)")

    if args.board:
        board_path = os.path.join(REPO, BOARD_REL)
        os.makedirs(os.path.dirname(board_path), exist_ok=True)
        open(board_path, "w", encoding="utf-8").write(build_board(docs))
        print(f"wrote {rel(board_path)}")

    if args.report:
        out = os.path.join(REPO, "docs", "_lifecycle.json")
        payload = report(docs, out)
        s = payload["summary"]
        print(f"[report] total={s['total']} registered={s['registered']} "
              f"unregistered={s['unregistered']} orphans={s['orphans']} "
              f"dup_groups={s['duplicate_groups']}")
        print(f"         by_type={s['by_type']}")
        print(f"         by_status={s['by_status']}")
        print(f"         wrote {rel(out)}")

    if args.check:
        errors, warns, stats = check(docs, index_path)
        limit = None if args.verbose else 20
        for w in warns[:limit]:
            print(f"WARN  {w}")
        if limit and len(warns) > limit:
            print(f"... 另有 {len(warns) - limit} 条告警（--verbose 查看）")
        for e in errors:
            print(f"ERROR {e}")
        print(f"[check] total={stats['total']} registered={stats['registered']} "
              f"unregistered={stats['unregistered']} errors={stats['errors']} warnings={stats['warnings']}")
        return 1 if errors else 0

    if not (args.index or args.report or args.check or args.board):
        ap.print_help()
    return 0


if __name__ == "__main__":
    sys.exit(main())
